function getArrFullByInterval(interval: number, dataReturnApi: Report[]): Report[] {
  const arrIndex: number[] = [];
  let arrByInterval: Report[] = [];
  if (interval === 5) {
    arrByInterval = fiveInterval;
  }
  if (interval === 10) {
    arrByInterval = tenInterval;
  }
  if (interval === 15) {
    arrByInterval = fifthteenInterval;
  }
  dataReturnApi.forEach((x) => {
    arrIndex.push(
      _.findIndex(arrByInterval, (o) => {
        return _.isMatch(
          { from: o.from.toString(), to: x.to?.toString() },
          { from: x.from.toString(), to: o.to?.toString() },
        );
      }),
    );
  });
  arrIndex.forEach((x, i) => {
    arrByInterval[x].numberOfLeague = dataReturnApi[i].numberOfLeague;
    arrByInterval[x].numberOfMatch = dataReturnApi[i].numberOfMatch;
    arrByInterval[x].beforeHDP = dataReturnApi[i].beforeHDP;
    arrByInterval[x].afterHDP = dataReturnApi[i].afterHDP;
    arrByInterval[x].beforeOU = dataReturnApi[i].beforeOU;
    arrByInterval[x].afterOU = dataReturnApi[i].afterOU;
    arrByInterval[x].diffHDP = dataReturnApi[i].diffHDP;
    arrByInterval[x].diffOU = dataReturnApi[i].diffOU;
  });
  return arrByInterval;
}
const FullByInterval = (interval: number, dataReturnApi: Report[]): Report[] | undefined => {
  const arrResult = getArrFullByInterval(interval, dataReturnApi);
  return arrResult;
};

export default FullByInterval;
